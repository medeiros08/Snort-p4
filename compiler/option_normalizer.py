import re


CONTENT_MODIFIERS = {
    "fast_pattern",
    "fast_pattern_offset",
    "fast_pattern_length",
    "nocase",
    "width",
    "endian",
    "offset",
    "depth",
    "distance",
    "within",
}


INTEGER_MODIFIERS = {
    "fast_pattern_offset",
    "fast_pattern_length",
    "offset",
    "depth",
    "distance",
    "within",
    "width",
}


FLAG_MODIFIERS = {
    "fast_pattern",
    "nocase",
}


def find_content_modifier_separator(value):
    """
    Locate the comma after the closing quote of a content
    expression.

    Parser examples:

        abc",nocase
        abc",depth 10
        !"abc",within 20

    Commas inside the actual content pattern are ignored.
    """

    escaped = False

    for index, char in enumerate(value):

        if escaped:
            escaped = False
            continue

        if char == "\\":
            escaped = True
            continue

        if char != '"':
            continue

        next_index = index + 1

        if (
            next_index < len(value)
            and value[next_index] == ","
        ):
            return next_index

    return None


def split_content_value(value):
    """
    Separate the content pattern from its modifier suffix.

    Returns:

        pattern
        modifier_strings
    """

    separator = find_content_modifier_separator(
        value
    )

    if separator is None:
        return value, []

    pattern = value[
        :separator
    ].strip()

    suffix = value[
        separator + 1:
    ].strip()

    modifiers = [
        part.strip()
        for part in suffix.split(",")
        if part.strip()
    ]

    return pattern, modifiers


def normalize_modifier(raw_modifier):
    """
    Convert a raw modifier string into a structured object.

    Examples:

        nocase

    becomes:

        {
            "name": "nocase",
            "value": True
        }

        depth 16

    becomes:

        {
            "name": "depth",
            "value": 16
        }
    """

    text = raw_modifier.strip()

    if not text:
        return None

    parts = text.split(
        None,
        1,
    )

    name = parts[0].lower()

    if name not in CONTENT_MODIFIERS:
        return {
            "name": name,
            "value": (
                parts[1]
                if len(parts) > 1
                else None
            ),
            "recognized": False,
        }

    if len(parts) == 1:

        return {
            "name": name,
            "value": True,
            "recognized": True,
        }

    raw_value = parts[1].strip()

    if name in INTEGER_MODIFIERS:

        try:
            value = int(
                raw_value
            )

        except ValueError:

            # Some positional parameters may eventually
            # reference values generated by byte_extract.
            value = raw_value

    else:
        value = raw_value

    return {
        "name": name,
        "value": value,
        "recognized": True,
    }


def remove_final_quote(pattern):
    """
    The current parser strips the opening content quote but
    may leave its closing quote.

    Example:

        abc"

    becomes:

        abc

    Negation is retained:

        !"abc"

    becomes:

        !"abc
    """

    pattern = pattern.strip()

    if pattern.endswith('"'):
        return pattern[:-1]

    return pattern


def normalize_content(value):
    """
    Normalize one parser content value.

    Example input:

        !"|00|",within 100,distance 2

    Output:

        {
            "pattern": "!\\"|00|",
            "negated": True,
            "modifiers": [
                {
                    "name": "within",
                    "value": 100,
                    "recognized": True
                },
                {
                    "name": "distance",
                    "value": 2,
                    "recognized": True
                }
            ]
        }
    """

    raw_pattern, raw_modifiers = (
        split_content_value(
            value
        )
    )

    pattern = remove_final_quote(
        raw_pattern
    )

    negated = False

    if pattern.startswith('!"'):
        negated = True
        pattern = pattern[2:]

    elif pattern.startswith("!"):
        negated = True
        pattern = pattern[1:]

    # Some parser forms may still retain an opening quote.
    if pattern.startswith('"'):
        pattern = pattern[1:]

    modifiers = []

    for raw_modifier in raw_modifiers:

        normalized = normalize_modifier(
            raw_modifier
        )

        if normalized is not None:
            modifiers.append(
                normalized
            )

    return {
        "pattern": pattern,
        "negated": negated,
        "modifiers": modifiers,
    }