import json
from collections import Counter
from pathlib import Path

from p4_backend import build_p4_entry

import pipeline_gate


MANIFEST_FILE = "../output/semantic_manifest.json"
OUTPUT_FILE = "../output/p4_entries.json"


def main():
    manifest_path = Path(
        MANIFEST_FILE
    )

    output_path = Path(
        OUTPUT_FILE
    )

    if not manifest_path.exists():
        print(
            f"ERROR: Manifest not found: "
            f"{manifest_path.resolve()}"
        )
        return

    with open(
        manifest_path,
        "r",
        encoding="utf-8",
    ) as file:
        manifest = json.load(file)

    rules = manifest.get(
        "rules",
        [],
    )

    entries = []

    skipped = 0
    failed = 0

    skipped_by_class = Counter()
    generated_by_class = Counter()

    rules_with_empty_match = []
    rules_with_expansion = []

    for rule_manifest in rules:

        rule_id = rule_manifest.get(
            "rule_id"
        )

        classification = (
            rule_manifest.get(
                "classification"
            )
        )

        try:
            entry = build_p4_entry(
                rule_manifest
            )

            if entry is None:

                skipped += 1

                skipped_by_class[
                    classification
                ] += 1

                continue

            entries.append(
                entry
            )

            generated_by_class[
                classification
            ] += 1

            # ------------------------------------------------
            # Sanity check:
            #
            # A semantic prefilter candidate should normally
            # result in at least one concrete backend match.
            # ------------------------------------------------

            if not entry.get(
                "match"
            ):

                rules_with_empty_match.append(
                    str(rule_id)
                )

            # ------------------------------------------------
            # Keep track of rules requiring finite expansion.
            # ------------------------------------------------

            if entry.get(
                "expansion_fields"
            ):

                rules_with_expansion.append(
                    str(rule_id)
                )

        except Exception as error:

            failed += 1

            print()
            print(
                f"Failed SID "
                f"{rule_id}: "
                f"{error}"
            )

    # ========================================================
    # Output structure
    # ========================================================

    output = {
        "schema_version": "2.0",

        "source_manifest": str(
            manifest_path.name
        ),

        "source_manifest_schema": (
            manifest.get(
                "schema_version"
            )
        ),

        "total_manifest_rules": len(
            rules
        ),

        "generated_entries": len(
            entries
        ),

        "skipped_rules": skipped,

        "failed_rules": failed,

        "generated_by_classification": dict(
            generated_by_class
        ),

        "skipped_by_classification": dict(
            skipped_by_class
        ),

        "rules_with_empty_match": (
            rules_with_empty_match
        ),

        "rules_with_expansion": (
            rules_with_expansion
        ),

        "entries": entries,
    }

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(
        output_path,
        "w",
        encoding="utf-8",
        newline="\n",
    ) as file:

        json.dump(
            output,
            file,
            indent=2,
            ensure_ascii=False,
        )

    # ========================================================
    # Report
    # ========================================================

    print()
    print(
        "=== P4 Backend Entry Generation ==="
    )
    print()

    print(
        f"Manifest rules          : "
        f"{len(rules)}"
    )

    print(
        f"Generated entries       : "
        f"{len(entries)}"
    )

    print(
        f"Skipped rules           : "
        f"{skipped}"
    )

    print(
        f"Failed rules            : "
        f"{failed}"
    )

    print()

    print(
        "Generated by classification"
    )
    print(
        "-" * 50
    )

    for classification in [
        "EXACT",
        "NECESSARY",
        "UNSUPPORTED",
    ]:

        print(
            f"{classification:<15} "
            f"{generated_by_class[classification]:>5}"
        )

    print()

    print(
        "Skipped by classification"
    )
    print(
        "-" * 50
    )

    for classification in [
        "EXACT",
        "NECESSARY",
        "UNSUPPORTED",
    ]:

        print(
            f"{classification:<15} "
            f"{skipped_by_class[classification]:>5}"
        )

    print()

    print(
        f"Rules requiring expansion : "
        f"{len(rules_with_expansion)}"
    )

    print(
        f"Rules with empty match     : "
        f"{len(rules_with_empty_match)}"
    )

    if rules_with_empty_match:

        print()
        print(
            "WARNING: candidate rules "
            "with empty backend match"
        )
        print(
            "-" * 60
        )

        for rule_id in (
            rules_with_empty_match[:50]
        ):

            print(
                f"SID {rule_id}"
            )

    print()

    print(
        f"Output:"
    )

    print(
        output_path.resolve()
    )


    pipeline_gate.aplicar(
        OUTPUT_FILE
    )

if __name__ == "__main__":
    main()